-- Axon Framework JPA Event Store Tables for H2

-- Domain Event Entry Table
CREATE TABLE IF NOT EXISTS DOMAIN_EVENT_ENTRY (
                                                  GLOBAL_INDEX BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  EVENT_IDENTIFIER VARCHAR(255) NOT NULL UNIQUE,
    META_DATA BLOB,
    PAYLOAD BLOB NOT NULL,
    PAYLOAD_REVISION VARCHAR(255),
    PAYLOAD_TYPE VARCHAR(255) NOT NULL,
    TIME_STAMP VARCHAR(255) NOT NULL,
    AGGREGATE_IDENTIFIER VARCHAR(255) NOT NULL,
    SEQUENCE_NUMBER BIGINT NOT NULL,
    TYPE VARCHAR(255),
    UNIQUE (AGGREGATE_IDENTIFIER, SEQUENCE_NUMBER)
    );

-- Snapshot Event Entry Table
CREATE TABLE IF NOT EXISTS SNAPSHOT_EVENT_ENTRY (
                                                    EVENT_IDENTIFIER VARCHAR(255) NOT NULL PRIMARY KEY,
    META_DATA BLOB,
    PAYLOAD BLOB NOT NULL,
    PAYLOAD_REVISION VARCHAR(255),
    PAYLOAD_TYPE VARCHAR(255) NOT NULL,
    TIME_STAMP VARCHAR(255) NOT NULL,
    AGGREGATE_IDENTIFIER VARCHAR(255) NOT NULL,
    SEQUENCE_NUMBER BIGINT NOT NULL,
    TYPE VARCHAR(255),
    UNIQUE (AGGREGATE_IDENTIFIER, SEQUENCE_NUMBER)
    );

-- Association Value Entry Table (pour les Sagas)
CREATE TABLE IF NOT EXISTS ASSOCIATION_VALUE_ENTRY (
                                                       ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                       ASSOCIATION_KEY VARCHAR(255) NOT NULL,
    ASSOCIATION_VALUE VARCHAR(255),
    SAGA_ID VARCHAR(255) NOT NULL,
    SAGA_TYPE VARCHAR(255)
    );

-- Saga Entry Table
CREATE TABLE IF NOT EXISTS SAGA_ENTRY (
                                          SAGA_ID VARCHAR(255) NOT NULL PRIMARY KEY,
    REVISION VARCHAR(255),
    SAGA_TYPE VARCHAR(255),
    SERIALIZED_SAGA BLOB
    );

-- Token Entry Table (pour le tracking des Event Processors)
CREATE TABLE IF NOT EXISTS TOKEN_ENTRY (
                                           PROCESSOR_NAME VARCHAR(255) NOT NULL,
    SEGMENT INT NOT NULL,
    OWNER VARCHAR(255),
    TIMESTAMP VARCHAR(255) NOT NULL,
    TOKEN BLOB,
    TOKEN_TYPE VARCHAR(255),
    PRIMARY KEY (PROCESSOR_NAME, SEGMENT)
    );

-- Dead Letter Entry Table (pour les événements en erreur)
CREATE TABLE IF NOT EXISTS DEAD_LETTER_ENTRY (
                                                 DEAD_LETTER_ID VARCHAR(255) NOT NULL PRIMARY KEY,
    CAUSE_MESSAGE VARCHAR(1024),
    CAUSE_TYPE VARCHAR(255),
    DIAGNOSTICS BLOB,
    ENQUEUED_AT VARCHAR(255) NOT NULL,
    LAST_TOUCHED VARCHAR(255),
    AGGREGATE_IDENTIFIER VARCHAR(255),
    EVENT_IDENTIFIER VARCHAR(255) NOT NULL,
    MESSAGE_TYPE VARCHAR(255) NOT NULL,
    META_DATA BLOB,
    PAYLOAD BLOB NOT NULL,
    PAYLOAD_REVISION VARCHAR(255),
    PAYLOAD_TYPE VARCHAR(255) NOT NULL,
    SEQUENCE_NUMBER BIGINT,
    TIME_STAMP VARCHAR(255) NOT NULL,
    TOKEN BLOB,
    TOKEN_TYPE VARCHAR(255),
    TYPE VARCHAR(255),
    PROCESSING_GROUP VARCHAR(255) NOT NULL,
    PROCESSING_STARTED VARCHAR(255),
    SEQUENCE_INDEX BIGINT NOT NULL
    );

-- Indexes pour améliorer les performances
CREATE INDEX IF NOT EXISTS IDX_DOMAIN_EVENT_AGGREGATE ON DOMAIN_EVENT_ENTRY(AGGREGATE_IDENTIFIER, SEQUENCE_NUMBER);
CREATE INDEX IF NOT EXISTS IDX_SNAPSHOT_EVENT_AGGREGATE ON SNAPSHOT_EVENT_ENTRY(AGGREGATE_IDENTIFIER, SEQUENCE_NUMBER);
CREATE INDEX IF NOT EXISTS IDX_ASSOCIATION_VALUE_ENTRY ON ASSOCIATION_VALUE_ENTRY(SAGA_ID, SAGA_TYPE);
CREATE INDEX IF NOT EXISTS IDX_SAGA_ENTRY ON SAGA_ENTRY(SAGA_TYPE);
CREATE INDEX IF NOT EXISTS IDX_DEAD_LETTER_ENTRY ON DEAD_LETTER_ENTRY(PROCESSING_GROUP, SEQUENCE_INDEX);